class Task(models.Model):
    _name = 'church.ops.task'
    _description = 'Church work item'
    _order = 'due_date, id'
    name = fields.Char(required=True)
    member_id = fields.Many2one('res.partner', index=True, ondelete='restrict')
    assigned_to_id = fields.Many2one('hr.employee', required=True, index=True)
    created_by_id = fields.Many2one('hr.employee', required=True)
    due_date = fields.Date(required=True, index=True)
    kind = fields.Selection([(v, v.replace('_', ' ').title()) for v in
        ('follow_up', 'visitor', 'verification', 'pledge', 'absence', 'general')], required=True)
    state = fields.Selection([('open', 'Open'), ('done', 'Completed'), ('cancelled', 'Cancelled')], default='open', required=True, index=True)
    completed_at = fields.Datetime(readonly=True)
    outcome = fields.Text()

    def write(self, vals):
        before = {r.id: r.state for r in self}
        result = super().write(vals)
        for rec in self:
            if before[rec.id] != rec.state or any(k in vals for k in ('assigned_to_id', 'due_date')):
                audit(self.env, self._name, rec.id, rec.member_id.id, 'Task updated', vals.keys())
        return result


