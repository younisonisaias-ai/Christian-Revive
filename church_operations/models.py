class Refund(models.Model):
    _name = 'church.ops.refund'
    _inherit = 'church.ops.append.only'
    _description = 'Recorded donation refund'
    _order = 'id desc'
    transaction_id = fields.Many2one('church.give.transaction', required=True, index=True, ondelete='restrict')
    staff_id = fields.Many2one('hr.employee', required=True)
    amount = fields.Float(required=True, digits=(16, 2))
    reference = fields.Char(required=True)
    reason = fields.Text(required=True)
    _unique_reference = models.Constraint('unique(transaction_id, reference)', 'This refund reference is already recorded.')

    @api.constrains('amount', 'transaction_id')
    def _valid_amount(self):
        for rec in self:
            try:
                money(rec.amount)
                returned = sum(rec.transaction_id.church_refund_ids.mapped('amount'))
                refund_net(rec.transaction_id.amount, returned, 'completed')
            except ValueError as exc:
                raise ValidationError(str(exc))


class Member(models.Model):
    _inherit = 'res.partner'
    church_name_key = fields.Char(compute='_church_keys', store=True, index=True)
    church_email_key = fields.Char(compute='_church_keys', store=True, index=True)
    church_phone_key = fields.Char(compute='_church_keys', store=True, index=True)
    church_visitor_owner_id = fields.Many2one('hr.employee', string='Visitor follow-up owner', index=True)
    church_next_contact_date = fields.Date(index=True)

    @api.depends('name', 'email', 'phone')
    def _church_keys(self):
        for rec in self:
            rec.church_name_key, rec.church_email_key, rec.church_phone_key = contact_keys(rec.name, rec.email, rec.phone)

    def write(self, vals):
        result = super().write(vals)
        relevant = set(vals) & {'name', 'phone', 'email', 'family_id', 'is_family_head',
            'membership_status', 'family_verified', 'leader_role', 'care_status',
            'visitor_stage', 'church_visitor_owner_id', 'church_next_contact_date'}
        if relevant:
            for rec in self.filtered(lambda p: p.is_member or p.visitor_stage):
                audit(self.env, 'res.partner', rec.id, rec.id, 'Profile updated', relevant)
        return result


class Transaction(models.Model):
    _inherit = 'church.give.transaction'
    church_refund_ids = fields.One2many('church.ops.refund', 'transaction_id')
    church_net_amount = fields.Float(compute='_church_net', store=True, digits=(16, 2))
    church_net_pkr = fields.Float(compute='_church_net', store=True, digits=(16, 2))
    church_pledge_credit = fields.Float('Verified original pledge credit', digits=(16, 2))
    church_credit_verified = fields.Boolean()
    church_reconciled = fields.Boolean('Statement verified', index=True, readonly=True)

    @api.depends('amount', 'amount_pkr', 'state', 'church_refund_ids.amount')
    def _church_net(self):
        for tx in self:
            returned = sum(tx.church_refund_ids.mapped('amount'))
            net = 0 if tx.state == 'refunded' else max(0, tx.amount - returned)
            tx.church_net_amount = net
            tx.church_net_pkr = tx.amount_pkr * net / tx.amount if tx.amount else 0

    def write(self, vals):
        if set(vals) & {'amount', 'currency', 'gateway_reference'} and not self.env.context.get('church_ops_reconcile'):
            vals = dict(vals, church_reconciled=False)
        if set(vals) & {'amount', 'currency', 'pledge_id'} and not self.env.context.get('church_ops_reconcile'):
            vals = dict(vals, church_credit_verified=False)
        result = super().write(vals)
        if set(vals) & {'state', 'amount', 'currency', 'pledge_id', 'church_credit_verified', 'church_pledge_credit'}:
            for tx in self:
                audit(self.env, self._name, tx.id, tx.partner_id.id, 'Donation updated', vals.keys())
        return result

    @api.constrains('amount', 'currency', 'church_refund_ids')
    def _church_refund_consistency(self):
        for tx in self:
            if tx.church_refund_ids and sum(tx.church_refund_ids.mapped('amount')) > tx.amount + 0.000001:
                raise ValidationError('The donation amount cannot be less than its recorded refunds.')

    @api.model
    def app_get_transactions(self, *args, **kwargs):
        rows = super().app_get_transactions(*args, **kwargs)
        if isinstance(rows, list):
            records = {r.id: r for r in self.sudo().browse([v['id'] for v in rows]).exists()}
            for row in rows:
                tx = records.get(row['id'])
                if tx:
                    row.update(net_amount=tx.church_net_amount, refunded_amount=tx.amount - tx.church_net_amount)
        return rows

    @api.model
    def app_get_totals(self, *args, **kwargs):
        data = kwargs or next((v for v in args if isinstance(v, dict)), {})
        uid = data.get('app_user_id')
        if not uid:
            return {}
        totals = {}
        rows = self.sudo()._read_group([('state', '=', 'completed'), ('app_user_id', '=', uid)],
            ['category_id'], ['church_net_pkr:sum'])
        for category, value in rows:
            totals[category.name if category else 'Other'] = {'total_pkr': value}
        return totals


class Pledge(models.Model):
    _inherit = 'church.give.pledge'
    church_balance_review = fields.Boolean(compute='_compute_paid_amount')

    def _compute_paid_amount(self):
        for pledge in self:
            txs = self.env['church.give.transaction'].sudo().search([
                ('pledge_id', '=', pledge.id), ('state', 'in', ['completed', 'refunded'])])
            paid, review = 0.0, False
            for tx in txs:
                if tx.state == 'refunded':
                    continue
                if pledge.currency == tx.currency:
                    paid += tx.church_net_amount
                elif pledge.currency == 'PKR':
                    paid += tx.church_net_pkr
                elif tx.church_credit_verified:
                    paid += tx.church_pledge_credit * tx.church_net_amount / tx.amount if tx.amount else 0
                else:
                    review = True  # Never add unrelated currency units or guess historic FX rates.
            pledge.paid_amount = paid
            pledge.progress_percent = min(100, paid * 100 / pledge.pledge_amount) if pledge.pledge_amount > 0 else 0
            pledge.church_balance_review = review

    def _read_pledges(self, pledges):
        rows = super()._read_pledges(pledges)
        lookup = {p.id: p for p in pledges}
        for row in rows:
            row['balance_needs_review'] = lookup[row['id']].church_balance_review
        return rows
