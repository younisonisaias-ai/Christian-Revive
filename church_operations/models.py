def audit(env, model, record_id, member_id, action, changed=()):
    # No private note bodies, old passwords or financial credentials in logs.
    if env.context.get('install_mode') or not env.registry.ready:
        return
    env['church.ops.audit'].sudo().with_context(church_audit_internal=True).create({
        'source_model': model, 'source_id': record_id, 'member_id': member_id or False,
        'action': action, 'changed_fields': ', '.join(sorted(changed)),
        'staff_id': env.context.get('church_ops_actor') or False,
        'odoo_user_id': env.uid,
    })


